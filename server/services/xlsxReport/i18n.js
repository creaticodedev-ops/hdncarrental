const getNested = (obj, path) =>
  path.split('.').reduce((acc, key) => (acc && acc[key] !== undefined ? acc[key] : undefined), obj);

export const SUPPORTED_LANGS = ['en', 'fr', 'es', 'ar'];

export const normalizeLang = (raw) => {
  const value = String(raw || '').toLowerCase().slice(0, 2);
  return SUPPORTED_LANGS.includes(value) ? value : 'en';
};

export const t = (lang, key, fallback = '') => {
  const locale = normalizeLang(lang);
  const value = getNested(DICTS[locale], key);
  if (typeof value === 'string') return value;
  const en = getNested(DICTS.en, key);
  if (typeof en === 'string') return en;
  return fallback || key;
};

export const monthName = (lang, monthIndex) => {
  const locale = normalizeLang(lang);
  const months = DICTS[locale]?.months || DICTS.en.months;
  return months[monthIndex] || DICTS.en.months[monthIndex] || '';
};

export const labelStatus = (lang, code) => {
  if (!code && code !== 0) return '';
  const key = String(code);
  return t(lang, `status.${key}`, key.replace(/_/g, ' '));
};

export default { t, normalizeLang, monthName, labelStatus, SUPPORTED_LANGS };
